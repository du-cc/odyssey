const fileLogoCache = {};

const SCALE_TO_UNIFORM_AREA = true;
let trailerWidth = 0;
let trailerHeight = 0;

function getMeasurements(){
  const rect = trailer.getBoundingClientRect();
  trailerWidth = rect.width;
  trailerHeight = trailerWidth / 1.43;
}

function getBaseTrailerArea(){
  return trailerWidth / +('2.39:1'.split(':')[0]) * trailerWidth;
}

function getTrailerScaleFactor(ratio, width = trailerWidth){
  const area = width / +(ratio.split(':')[0]) * width;
  return Math.sqrt(getBaseTrailerArea() / area);
}

function getObscuringBarHeight(ratio, width = trailerWidth, height = trailerHeight){
  const diff = height - width / +(ratio.split(':')[0]);
  return Math.max(0, diff / 2 + 1);
}

function getObscuringBarsMeasurements(ratio){
  let topBottomBarHeight = 0;
  let sideBarWidth = 0;
  const sideBarHeight = trailerHeight;

  topBottomBarHeight = getObscuringBarHeight(ratio);
  let scaleFactor = getTrailerScaleFactor(ratio);

  if(ratio === '1.85:1'){
    const flatWidth = trailerWidth * (3996 / 4096);
    sideBarWidth = Math.max(0, (trailerWidth - flatWidth) / 2 + 1);
    topBottomBarHeight = getObscuringBarHeight(ratio, flatWidth);
    scaleFactor = getTrailerScaleFactor(ratio, flatWidth);
  }

  return { topBottomBarHeight, sideBarWidth, sideBarHeight, scaleFactor };
}

function applyBars(ratio){
  getMeasurements();
  const { topBottomBarHeight, sideBarWidth, sideBarHeight, scaleFactor } = getObscuringBarsMeasurements(ratio);

  topBar.style.height = `${topBottomBarHeight}px`;
  bottomBar.style.height = `${topBottomBarHeight}px`;
  leftBar.style.width = `${sideBarWidth}px`;
  leftBar.style.height = `${sideBarHeight}px`;
  rightBar.style.width = `${sideBarWidth}px`;
  rightBar.style.height = `${sideBarHeight}px`;

  trailerBox.classList.toggle('scale-to-uniform-area', SCALE_TO_UNIFORM_AREA);
  trailerBox.style.transform = SCALE_TO_UNIFORM_AREA ? `scale(${scaleFactor})` : '';
}

async function getFileLogoMarkup(file){
  if(fileLogoCache[file]) return fileLogoCache[file];
  let markup;
  try{
    const res = await fetch(file);
    if(!res.ok) throw new Error('fetch failed');
    markup = await res.text();
  }catch(e){
    markup = `<img src="${file}" alt="">`;
  }
  fileLogoCache[file] = markup;
  return markup;
}

function logoMarkupFor(f){
  if(f.logoHTML) return Promise.resolve(f.logoHTML);
  if(f.logoFile) return getFileLogoMarkup(f.logoFile);
  return Promise.resolve(`<span class="format-logo-text">${f.logoText || ''}</span>`);
}

function buildButtons(){
  formatRow.innerHTML = '';
  formats.forEach((f, i) => {
    const hasAlt = !!f.altRatio;
    const ratioHTML = hasAlt
      ? `<div class="format-alt-ratios"><span class="format-ratio">${f.ratio}</span><span class="format-ratio">${f.altRatio}</span></div>`
      : `<span class="format-ratio">${f.ratio}</span>`;
    const btn = document.createElement('button');
    btn.className = 'format-btn' + (i === activeIndex ? ' active' : '') + (hasAlt ? ' has-alt' : '');
    btn.innerHTML = `
      <div class="format-graphic">${f.icon}</div>
      <div class="format-logo" data-logo-slot="${i}"></div>
      ${ratioHTML}
    `;
    btn.addEventListener('click', () => selectFormat(i));
    formatRow.appendChild(btn);

    logoMarkupFor(f).then(markup => {
      const slot = btn.querySelector(`[data-logo-slot="${i}"]`);
      if(slot) slot.innerHTML = markup;
    });
  });
}

async function selectFormat(i){
  activeIndex = i;
  [...formatRow.children].forEach((btn, idx) => btn.classList.toggle('active', idx === i));
  const f = formats[i];
  applyBars(f.ratio);
  fdName.textContent = `${f.label} · ${f.ratio}${f.altRatio ? ' / ' + f.altRatio : ''}`;
  fdDesc.innerHTML = f.desc;
  fdLogo.innerHTML = await logoMarkupFor(f);
}

function onWindowResize(){
  applyBars(formats[activeIndex].ratio);
}
window.addEventListener('resize', onWindowResize);

function handleFile(file){
  if(!file) return;
  if(objectUrl) URL.revokeObjectURL(objectUrl);
  objectUrl = URL.createObjectURL(file);
  uploadState.style.display = 'none';

  if(file.type.startsWith('video/')){
    imageEl.hidden = true;
    imageEl.src = '';
    videoEl.src = objectUrl;
    videoEl.hidden = false;
    videoEl.play().catch(()=>{});
  } else if(file.type.startsWith('image/')){
    videoEl.hidden = true;
    videoEl.pause();
    videoEl.src = '';
    imageEl.src = objectUrl;
    imageEl.hidden = false;
  } else {
    uploadState.style.display = 'flex';
    return;
  }

  changeRow.hidden = false;
}

